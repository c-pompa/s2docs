"""Generate ``plugin/skills/<skill>/references/tools.md`` from a LIVE ``tools/list``.

The plugin skill's tool table must describe the server that actually ships, so it is generated
from an MCP handshake rather than hand-written (an earlier hand-list drifted from the registry as
soon as tools were added). Two launch paths, and the default measures *this* checkout:

  python scripts/plugin_tools_md.py                    # this tree: python -m s2docs.cli mcp
  python scripts/plugin_tools_md.py --from-manifest     # exactly what plugin/mcp.json declares

``--from-manifest`` clones/builds the pinned git ref from scratch, so it needs the repository
reachable; use it as the release check, not per edit. Exit code is non-zero when the handshake
yields no tools (a "0 tools" table would look like a working server with nothing in it).
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PLUGIN_DIR = REPO_ROOT / "plugin"
SKILL_DIR = PLUGIN_DIR / "skills" / "s2docs-source2"
TABLE_PATH = SKILL_DIR / "references" / "tools.md"

# stdio MCP servers get a filtered environment (no API keys), so the probe passes the same subset.
_PASSTHROUGH = ("PATH", "HOME", "USER", "LANG", "LC_ALL", "TERM", "SHELL", "TMPDIR")


def _base_env(data_dir: Path | None) -> dict[str, str]:
    env = {key: os.environ[key] for key in _PASSTHROUGH if key in os.environ}
    if data_dir is not None:
        env["S2DOCS_DATA_DIR"] = str(data_dir)
    return env


def _manifest_command() -> tuple[str, list[str], dict[str, str]]:
    manifest = json.loads((PLUGIN_DIR / "mcp.json").read_text())
    servers = manifest["mcpServers"]
    if len(servers) != 1:
        raise SystemExit(f"expected exactly one server in mcp.json, found {sorted(servers)}")
    name, server = next(iter(servers.items()))
    if server.get("type") != "stdio":
        raise SystemExit(f"server {name!r} is {server.get('type')!r}; this probe speaks stdio")
    return server["command"], list(server.get("args", [])), dict(server.get("env", {}))


async def _list_tools(command: str, args: list[str], env: dict[str, str]) -> list[dict]:
    from mcp import ClientSession, StdioServerParameters, types
    from mcp.client.stdio import stdio_client

    params = StdioServerParameters(command=command, args=args, env=env)
    async with stdio_client(params) as (read, write), ClientSession(read, write) as session:
        init = await session.initialize()
        print(f"server: {init.server_info.name} {init.server_info.version}", file=sys.stderr)
        page = await session.list_tools()
        tools = list(page.tools)
        while page.next_cursor:
            page = await session.list_tools(params=types.PaginatedRequestParams(cursor=page.next_cursor))
            tools.extend(page.tools)
    rows = []
    for tool in tools:
        annotations = tool.annotations
        rows.append({
            "name": tool.name,
            "summary": _summary(tool.description or ""),
            "read_only": bool(getattr(annotations, "read_only_hint", False)) if annotations else False,
        })
    return sorted(rows, key=lambda row: row["name"])


def _summary(description: str) -> str:
    """First sentence of a tool description, whitespace-collapsed (docstrings wrap mid-sentence)."""
    text = " ".join(description.split())
    head, sep, _tail = text.partition(". ")
    candidate = head if sep and len(head) <= 200 else text
    return candidate if len(candidate) <= 200 else candidate[:197].rstrip() + "..."


def _render(rows: list[dict], origin: str) -> str:
    read_only = sum(1 for row in rows if row["read_only"])
    lines = [
        "# s2docs tools",
        "",
        "Generated by `scripts/plugin_tools_md.py` from a live `tools/list` — do not hand-edit.",
        f"Origin of this capture: {origin}.",
        "",
        f"{len(rows)} tools ({read_only} read-only, {len(rows) - read_only} write-capable). "
        "Write-capable tools are gated by the plugin's `trust: untrusted` declaration, so Hermes asks "
        "the user before each call.",
        "",
        "| tool | kind | summary |",
        "|---|---|---|",
    ]
    for row in rows:
        summary = row["summary"].replace("|", "\\|")
        lines.append(f"| `{row['name']}` | {'read' if row['read_only'] else 'write'} | {summary} |")
    lines.append("")
    return "\n".join(lines)


async def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from-manifest", action="store_true",
                        help="launch exactly what plugin/mcp.json declares (needs the pinned ref reachable)")
    parser.add_argument("--data-dir", default="",
                        help="data dir for the probe (default: a throwaway temp dir, never the real index)")
    args = parser.parse_args(argv)

    if args.data_dir:
        data_dir = Path(args.data_dir).expanduser().resolve()
    else:
        data_dir = Path(tempfile.mkdtemp(prefix="s2docs-probe-"))
    if args.from_manifest:
        command, mcp_args, manifest_env = _manifest_command()
        # Hermes expands ${VAR} refs from the profile; the probe has no profile, so it fills the data
        # dir itself (the one ref whose value decides which store gets touched) and leaves the rest
        # as written — that is what the server must tolerate.
        env = {**_base_env(data_dir),
               **{key: (str(data_dir) if value == "${S2DOCS_DATA_DIR}" else value)
                  for key, value in manifest_env.items()}}
        origin = f"`{command} {' '.join(mcp_args)}` (plugin/mcp.json)"
    else:
        command, mcp_args, env = sys.executable, ["-m", "s2docs.cli", "mcp"], _base_env(data_dir)
        origin = f"`{Path(sys.executable).name} -m s2docs.cli mcp` (this checkout)"

    rows = await _list_tools(command, mcp_args, env)
    if not rows:
        print("error: tools/list returned no tools — refusing to write an empty table", file=sys.stderr)
        return 2
    TABLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    TABLE_PATH.write_text(_render(rows, origin), encoding="utf-8")
    read_only = sum(1 for row in rows if row["read_only"])
    print(f"wrote {TABLE_PATH.relative_to(REPO_ROOT)}: {len(rows)} tools ({read_only} read-only)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
